// Retorna os 5 golpes básicos iniciais para uma modalidade
export function getStarterMovesForModality(modalityId) {
  return STARTER_MOVES[modalityId] || STARTER_MOVES.boxing;
}

// Retorna a lista de golpes especiais compráveis na Loja de Habilidades
// FILTRA ESTRITAMENTE PELA MODALIDADE DO LUTADOR!
// Se for Boxing, retorna APENAS golpes de Boxing. Se for Jiu-Jitsu, APENAS golpes de Jiu-Jitsu.
export function getShopMoves(modalityId = 'boxing') {
  const targetMod = modalityId || 'boxing';

  return Object.values(ALL_MOVES_DATABASE).filter(m => {
    if (m.isBasic) return false;
    // Se o golpe foi marcado para esta modalidade específica
    if (m.modalities && m.modalities.includes(targetMod)) {
      return true;
    }
    // No caso do MMA, tem acesso a golpes híbridos (boxing, muay thai, jiu-jitsu, wrestling) marcados para MMA
    if (targetMod === 'mma' && m.modalities && m.modalities.includes('mma')) {
      return true;
    }
    return false;
  });
}

// Retorna um golpe pelo seu ID
export function getMoveById(id) {
  return ALL_MOVES_DATABASE[id] || null;
}
